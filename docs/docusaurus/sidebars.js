import labelData from './src/data/labelRegistry.cjs';

const { labelRegistry, sharedNavigation, tierNavigation } = labelData;

function toSidebarItem(item) {
  if (item.type === 'doc') {
    return item;
  }

  if (item.docId && !item.dirName && !item.items) {
    return { type: 'doc', id: item.docId, label: item.label };
  }

  const sidebarItem = {
    type: 'category',
    label: item.label,
    items: item.items
      ? item.items.map(toSidebarItem)
      : [{ type: 'autogenerated', dirName: item.dirName }],
  };

  if (item.docId) {
    sidebarItem.link = { type: 'doc', id: item.docId };
  }

  return sidebarItem;
}

/** @type {import('@docusaurus/plugin-content-docs').SidebarsConfig} */
const sidebars = {
  docsSidebar: [
    { type: 'doc', id: 'README', label: labelRegistry.documentation },
    ...tierNavigation.map(({ label, docId, dirName }) => ({
      type: 'category',
      label,
      link: { type: 'doc', id: docId },
      items: [{ type: 'autogenerated', dirName }],
    })),
    ...sharedNavigation.map(toSidebarItem),
  ],
};

export default sidebars;
